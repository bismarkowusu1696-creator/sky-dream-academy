'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {correctPaymentInPlace}=require('../functions/payment-corrections');
function fixture(){return {id:'student-1',regNumber:'SDHD005/10/2026',fullName:'Example Student',status:'Registered',course:'hair-dressing',feePaid:100,payments:[{amount:100,date:'2026-10-16T09:00:00Z',note:'First payment',recordedBy:'manager'}],otherField:'untouched'};}
const params={paymentIndex:0,expectedAmount:100,expectedDate:'2026-10-16T09:00:00Z',newAmount:'50',reason:'Data entry correction: GHS 50 received'};
const s=fixture(),result=correctPaymentInPlace(s,params,'owner-admin','2026-10-16T10:00:00Z');
assert.equal(result.oldTotal,100);assert.equal(result.newTotal,50);
assert.equal(s.feePaid,50);assert.equal(s.payments.length,1);
assert.equal(s.payments[0].amount,50);assert.equal(s.payments[0].note,'First payment');
assert.equal(s.payments[0].recordedBy,'manager');
assert.equal(s.payments[0].corrections[0].previousAmount,100);
assert.equal(s.payments[0].corrections[0].newAmount,50);
assert.equal(s.payments[0].corrections[0].reason,params.reason);
assert.equal(s.otherField,'untouched');
const second=correctPaymentInPlace(s,{...params,expectedAmount:50,newAmount:40},'owner-admin','2026-10-16T11:00:00Z');
assert.equal(second.oldAmount,50);assert.equal(s.feePaid,40);
assert.equal(s.payments[0].corrections.length,2);
function denied(student,changes,code){const old=JSON.stringify(student);assert.throws(()=>correctPaymentInPlace(student,{...params,...changes},'owner-admin','2026-10-16T11:00:00Z'),e=>e.code===code);assert.equal(JSON.stringify(student),old,'Rejected correction must not modify records.');}
denied(fixture(),{newAmount:100},'invalid-argument');
denied(fixture(),{newAmount:-50},'invalid-argument');
denied(fixture(),{newAmount:'50.123'},'invalid-argument');
denied(fixture(),{paymentIndex:5},'invalid-argument');
denied(fixture(),{expectedAmount:99},'aborted');
denied(fixture(),{expectedDate:'2026-10-17'},'aborted');
denied(fixture(),{reason:'x'},'invalid-argument');
const mismatch=fixture();mismatch.feePaid=125;
denied(mismatch,{},'failed-precondition');
const multi=fixture();multi.payments=[{amount:50,date:'a'},{amount:50,date:'b'}];
correctPaymentInPlace(multi,{paymentIndex:1,expectedAmount:50,expectedDate:'b',newAmount:20,reason:'Entered the wrong amount'},'owner-admin','2026-10-16T12:00:00Z');
assert.deepEqual(multi.payments.map(p=>p.amount),[50,20]);assert.equal(multi.feePaid,70);
